/**
 * Simulation-based validation of the CogniTwin engine.
 *
 *   npm run validate            → writes docs/VALIDATION.md
 *
 * Synthetic users with KNOWN abilities are run through the real adaptive engine. Because the
 * truth is known, we can measure what real data cannot tell us directly: estimation error,
 * whether 80 % intervals really contain the truth 80 % of the time, tracking of learning,
 * calibration of projections, difficulty targeting, data-quality detection and the behaviour
 * of the AI Collaboration Score on archetypal users.
 *
 * Caveat (also stated in the report): the simulated responses follow the engine's own model,
 * so this validates the *machinery* (estimation, adaptivity, uncertainty), not the construct
 * validity of the tasks, which requires real participants.
 */
import { writeFileSync, mkdirSync } from 'node:fs';
import {
  DIMENSIONS,
  POPULATION_PRIOR,
  TARGET_SUCCESS,
  assessQuality,
  computeCollabScore,
  createRng,
  mastery,
  pSuccess,
  project,
  sessionPrior,
  simulateRun,
  trueAbility,
  updateBelief,
  applySession,
  createTwin,
  finalizeSession,
  modelFor,
  dimensionHistory,
  normCdf,
  type AIEvent,
  type ChallengePreference,
  type Observation,
  type Rng,
  type SimUser,
} from '../src/engine/index';

const SEED = 20261101;
const DAY = 86_400_000;
const t0 = performance.now();
const rng = createRng(SEED);
const lines: string[] = [];
const out = (s = '') => lines.push(s);
const f = (x: number, d = 2) => (Number.isFinite(x) ? x.toFixed(d) : '—');
const pct = (x: number) => `${(100 * x).toFixed(1)} %`;

const plainUser = (extra: Partial<SimUser> = {}): SimUser => ({ theta: {}, growth: {}, rtScale: 1, lapseRate: 0.02, interruptRate: 0, ...extra });

function pearson(a: number[], b: number[]) {
  const n = a.length;
  const ma = a.reduce((s, x) => s + x, 0) / n;
  const mb = b.reduce((s, x) => s + x, 0) / n;
  let sab = 0;
  let saa = 0;
  let sbb = 0;
  for (let i = 0; i < n; i++) {
    sab += (a[i] - ma) * (b[i] - mb);
    saa += (a[i] - ma) ** 2;
    sbb += (b[i] - mb) ** 2;
  }
  return sab / Math.sqrt(saa * sbb);
}

out('# Validation report (simulation)');
out();
out(`Generated by \`npm run validate\` on ${new Date().toISOString().slice(0, 10)} · seed ${SEED}.`);
out();
out('> **What this shows and what it does not.** Synthetic users with known abilities are run through the *real* engine. ' +
  'This measures the quality of the measurement machinery — estimation error, interval calibration, adaptivity, tracking and robustness. ' +
  'Simulated responses follow the engine’s own response model, so this does **not** establish that the tasks measure the intended constructs in real people; that requires a pilot study (see the technical report, “Limitations”).');
out();

// ------------------------------------------------------------------------------------------------
// 1. Parameter recovery, one assessment from the population prior
// ------------------------------------------------------------------------------------------------
out('## 1. Single-session recovery (computerised adaptive check-in)');
out();
out('300 synthetic users per dimension, true θ ~ N(0, 1), lapse rate 2 %. One adaptive check-in starting from the population prior.');
out();
out('| Dimension | Task | Pearson r | RMSE (θ) | Bias (θ) | 80 % interval coverage | Mean trials | Mean interval width (pts) |');
out('|---|---|---|---|---|---|---|---|');
const N1 = 300;
for (const d of DIMENSIONS) {
  const truth: number[] = [];
  const est: number[] = [];
  let covered = 0;
  let trials = 0;
  let width = 0;
  for (let i = 0; i < N1; i++) {
    const theta = rng.normal(0, 1);
    const res = simulateRun(d.task, plainUser(), { mode: 'assessment', prior: POPULATION_PRIOR, ability: theta, rng, startedAt: 0 });
    const b = res.session.belief;
    truth.push(theta);
    est.push(b.mean);
    if (Math.abs(b.mean - theta) <= 1.2816 * b.sd) covered++;
    trials += res.trials.length;
    width += mastery(b.mean + 1.2816 * b.sd, d.task) - mastery(b.mean - 1.2816 * b.sd, d.task);
  }
  const rmse = Math.sqrt(truth.reduce((s, x, i) => s + (x - est[i]) ** 2, 0) / N1);
  const bias = est.reduce((s, x, i) => s + (x - truth[i]), 0) / N1;
  out(`| ${d.name} | ${d.task.name} | ${f(pearson(truth, est))} | ${f(rmse)} | ${f(bias)} | ${pct(covered / N1)} | ${f(trials / N1, 1)} | ${f(width / N1, 1)} |`);
}
out();
out('Reading: a single 1–3 minute check-in already ranks users well (r) while its intervals stay honest (coverage close to the nominal 80 %). ' +
  'Widths of 20–30 points are why the app labels first results “moderate/low confidence”.');
out();

// ------------------------------------------------------------------------------------------------
// 2. Adaptive vs fixed design
// ------------------------------------------------------------------------------------------------
out('## 2. Why adaptive? CAT vs random-level design with the same number of trials');
out();
out('| Dimension | Trials | RMSE adaptive | RMSE random levels | Error reduction |');
out('|---|---|---|---|---|');
for (const id of ['speed', 'memory', 'reasoning']) {
  const d = DIMENSIONS.find((x) => x.id === id)!;
  const N = 200;
  let seA = 0;
  let seF = 0;
  let nTrials = 0;
  for (let i = 0; i < N; i++) {
    const theta = rng.normal(0, 1.2);
    const res = simulateRun(d.task, plainUser({ lapseRate: 0 }), { mode: 'assessment', prior: POPULATION_PRIOR, ability: theta, rng, startedAt: 0 });
    seA += (res.session.belief.mean - theta) ** 2;
    const n = res.trials.length;
    nTrials += n;
    const obs: Observation[] = Array.from({ length: n }, () => {
      const level = rng.int(1, d.task.levels);
      return { level, success: rng.chance(pSuccess(theta, level, d.task)) };
    });
    seF += (updateBelief(POPULATION_PRIOR, obs, d.task).mean - theta) ** 2;
  }
  const a = Math.sqrt(seA / N);
  const b = Math.sqrt(seF / N);
  out(`| ${d.name} | ${f(nTrials / N, 1)} | ${f(a)} | ${f(b)} | ${pct(1 - a / b)} |`);
}
out();

// ------------------------------------------------------------------------------------------------
// 3. Tracking learning over time (Brain Twin dynamics)
// ------------------------------------------------------------------------------------------------
out('## 3. Brain Twin tracking of real change');
out();
out('100 learners practise Working Memory every ~2 days for 40 days (true gain 0.6–1.4 logits, saturating). ' +
  'We compare the twin (with drift + per-session process noise) to a static Bayesian model that never forgets.');
out();
function tracking(useDrift: boolean, r: Rng) {
  const task = DIMENSIONS.find((x) => x.id === 'memory')!.task;
  let se = 0;
  let cov = 0;
  let n = 0;
  let lateSe = 0;
  let lateN = 0;
  for (let u = 0; u < 100; u++) {
    const user: SimUser = plainUser({ theta: { memory: r.normal(-0.3, 0.8) }, growth: { memory: 0.6 + r.next() * 0.8 } });
    let twin = createTwin(0);
    for (let s = 0; s < 20; s++) {
      const at = s * 2 * DAY + r.int(0, 6) * 3600_000;
      const ability = trueAbility(user, 'memory', s);
      const prior = useDrift ? sessionPrior(twin, 'memory', at) : { mean: twin.dims.memory.mean, sd: twin.dims.memory.sd };
      const res = simulateRun(task, user, { mode: 'training', prior, ability, rng: r, startedAt: at });
      const rec = finalizeSession({ id: `u${u}s${s}`, taskId: task.id, mode: 'training', startedAt: at, endedAt: res.endedAt, trials: res.trials, behaviour: res.behaviour, prior, deadlineFactor: 1 });
      twin = applySession(twin, rec);
      const after = trueAbility(user, 'memory', s + 1);
      // Compare with the ability that generated the session (the twin cannot see future learning).
      const err = rec.after.mean - ability;
      se += err ** 2;
      if (Math.abs(err) <= 1.2816 * rec.after.sd) cov++;
      n++;
      if (s >= 14) {
        lateSe += (rec.after.mean - after) ** 2;
        lateN++;
      }
    }
  }
  return { rmse: Math.sqrt(se / n), coverage: cov / n, lateRmse: Math.sqrt(lateSe / lateN) };
}
const withDrift = tracking(true, createRng(SEED + 1));
const noDrift = tracking(false, createRng(SEED + 1));
out('| Model | RMSE over all sessions | RMSE, last 6 sessions | 80 % interval coverage |');
out('|---|---|---|---|');
out(`| Brain Twin (drift ${'+'} process noise) | ${f(withDrift.rmse)} | ${f(withDrift.lateRmse)} | ${pct(withDrift.coverage)} |`);
out(`| Static Bayesian (no forgetting) | ${f(noDrift.rmse)} | ${f(noDrift.lateRmse)} | ${pct(noDrift.coverage)} |`);
out();
out('Reading: without drift the posterior becomes over-confident and lags behind real learning (coverage collapses to about a third). ' +
  'The twin’s drift keeps intervals close to honest while it follows growth. Coverage remains a little under the nominal 80 % because learners also improve *within* a session, which a per-session model cannot see — a known, documented limitation.');
out();

// ------------------------------------------------------------------------------------------------
// 4. Projection calibration
// ------------------------------------------------------------------------------------------------
out('## 4. Are projections honest?');
out();
out('After 8 sessions (≈ 16 days), each learner’s growth curve is projected 14 days ahead. We check how often the true future score falls inside the projected bands.');
out();
{
  const r = createRng(SEED + 2);
  const task = DIMENSIONS.find((x) => x.id === 'flexibility')!.task;
  let in80 = 0;
  let in50 = 0;
  let n = 0;
  let absErr = 0;
  for (let u = 0; u < 150; u++) {
    const user: SimUser = plainUser({ theta: { flexibility: r.normal(-0.2, 0.8) }, growth: { flexibility: r.next() * 1.4 } });
    let twin = createTwin(0);
    let at = 0;
    for (let s = 0; s < 8; s++) {
      at = s * 2 * DAY + 9 * 3600_000;
      const prior = sessionPrior(twin, 'flexibility', at);
      const res = simulateRun(task, user, { mode: 'training', prior, ability: trueAbility(user, 'flexibility', s), rng: r, startedAt: at });
      twin = applySession(twin, finalizeSession({ id: `p${u}${s}`, taskId: task.id, mode: 'training', startedAt: at, endedAt: res.endedAt, trials: res.trials, behaviour: res.behaviour, prior, deadlineFactor: 1 }));
    }
    const proj = project(dimensionHistory(twin, 'flexibility'), modelFor('flexibility'), at, 14);
    if (!proj.ok) continue;
    // Practice continues every 2 days → 7 more sessions by the horizon.
    const truth = mastery(trueAbility(user, 'flexibility', 15), task);
    const end = proj.projection.points.at(-1)!;
    if (truth >= end.lo80 && truth <= end.hi80) in80++;
    if (truth >= end.lo50 && truth <= end.hi50) in50++;
    absErr += Math.abs(truth - end.mid);
    n++;
  }
  out('| Horizon | Learners | Inside 50 % band | Inside 80 % band | Mean absolute error (pts) |');
  out('|---|---|---|---|---|');
  out(`| 14 days | ${n} | ${pct(in50 / n)} | ${pct(in80 / n)} | ${f(absErr / n, 1)} |`);
  out();
  out('Reading: coverage at or above nominal means the bands are, if anything, cautious — the intended behaviour for a feature that must “never present a projection as certainty”.');
  out();
}

// ------------------------------------------------------------------------------------------------
// 5. Difficulty targeting in training
// ------------------------------------------------------------------------------------------------
out('## 5. Difficulty targeting (training mode)');
out();
out('| Challenge preference | Target success | Observed success (6 tasks × 60 sessions) |');
out('|---|---|---|');
for (const pref of ['gentle', 'balanced', 'stretch'] as ChallengePreference[]) {
  let k = 0;
  let n = 0;
  for (const d of DIMENSIONS) {
    for (let i = 0; i < 60; i++) {
      const theta = rng.normal(0, 0.8);
      // A twin that already knows the user reasonably well.
      const prior = { mean: theta + rng.normal(0, 0.3), sd: 0.35 };
      const res = simulateRun(d.task, plainUser(), { mode: 'training', prior, ability: theta, rng, startedAt: 0, challenge: pref });
      k += res.trials.filter((t) => t.success).length;
      n += res.trials.length;
    }
  }
  out(`| ${pref} | ${pct(TARGET_SUCCESS[pref])} | ${pct(k / n)} |`);
}
out();

// ------------------------------------------------------------------------------------------------
// 6. Robustness: data quality
// ------------------------------------------------------------------------------------------------
out('## 6. Robustness: random pressing and interruptions');
out();
{
  const twoChoice = DIMENSIONS.filter((d) => d.task.guessing >= 0.2);
  let tp = 0;
  let fp = 0;
  let nr = 0;
  let ng = 0;
  for (const d of twoChoice) {
    for (let i = 0; i < 100; i++) {
      const rand = simulateRun(d.task, plainUser({ randomResponder: true }), { mode: 'training', prior: POPULATION_PRIOR, ability: 0, rng, startedAt: 0 });
      if (assessQuality(d.task, rand.trials, rand.behaviour).flags.some((x) => x.kind === 'random_responding')) tp++;
      nr++;
      const genuine = simulateRun(d.task, plainUser(), { mode: 'training', prior: POPULATION_PRIOR, ability: rng.normal(0, 1), rng, startedAt: 0 });
      if (assessQuality(d.task, genuine.trials, genuine.behaviour).flags.some((x) => x.kind === 'random_responding')) fp++;
      ng++;
    }
  }
  out(`Random-pressing detector on the ${twoChoice.length} two-choice tasks: **${pct(tp / nr)} detected**, **${pct(fp / ng)} false alarms** on genuine users.`);
  out();
  const task = DIMENSIONS.find((x) => x.id === 'inhibition')!.task;
  let errClean = 0;
  let errInt = 0;
  const N = 200;
  for (let i = 0; i < N; i++) {
    const theta = rng.normal(0, 1);
    const a = simulateRun(task, plainUser(), { mode: 'assessment', prior: POPULATION_PRIOR, ability: theta, rng, startedAt: 0 });
    const b = simulateRun(task, plainUser({ interruptRate: 1, lapseRate: 0.08 }), { mode: 'assessment', prior: POPULATION_PRIOR, ability: theta, rng, startedAt: 0 });
    errClean += (a.session.belief.mean - theta) ** 2;
    const q = assessQuality(task, b.trials, b.behaviour);
    const weighted = updateBelief(POPULATION_PRIOR, b.trials.map((t) => ({ level: t.level, success: t.success, weight: (t.weight ?? 1) * q.weight })), task);
    errInt += (weighted.mean - theta) ** 2;
  }
  out(`Heavily interrupted sessions (≈ 1 interruption per 10 trials, 4× lapses): RMSE ${f(Math.sqrt(errInt / N))} vs ${f(Math.sqrt(errClean / N))} for clean sessions — degraded but bounded, and flagged to the user.`);
  out();
}

// ------------------------------------------------------------------------------------------------
// 7. AI Collaboration Score on archetypes
// ------------------------------------------------------------------------------------------------
out('## 7. AI Collaboration Score — archetypes');
out();
out('Each archetype generates 40 interactions stochastically (200 replications). The score should separate effective collaboration from both failure modes (blind trust and disengagement) and report wider intervals for users with little evidence.');
out();
{
  type Arche = { name: string; gen: (r: Rng, i: number) => AIEvent | null };
  const e = (type: AIEvent['type'], data?: AIEvent['data']): AIEvent => ({ id: '', type, at: 0, data });
  const archetypes: Arche[] = [
    {
      name: 'Critical collaborator',
      gen: (r) =>
        r.pick([
          e('coach_message', { engaged: r.chance(0.6) }),
          e('why_opened'),
          e('chat_question', { clarifying: true, specificity: 0.8 }),
          e('recommendation_response', { response: r.chance(0.4) ? 'modified' : 'accepted', confidence: 'low', evidenceViewed: true }),
          e('verify_challenge', { found: r.chance(0.85) }),
          e('followup'),
          e('self_prediction', { predicted: 60, actual: 60 + r.normal(0, 6) }),
          e('session_completed', { hints: 0, hintsAvailable: true, reliability: 'good' }),
        ]),
    },
    {
      name: 'Over-reliant',
      gen: (r) =>
        r.pick([
          e('coach_message', { engaged: false }),
          e('recommendation_response', { response: 'accepted', confidence: r.chance(0.5) ? 'low' : 'moderate', evidenceViewed: false }),
          e('session_completed', { hints: r.int(1, 3), hintsAvailable: true, reliability: 'good' }),
          e('goal_from_ai'),
          e('verify_challenge', { found: r.chance(0.3) }),
          e('self_prediction', { predicted: 85, actual: 55 + r.normal(0, 8) }),
        ]),
    },
    {
      name: 'Disengaged / careless',
      gen: (r) =>
        r.pick([
          e('coach_message', { engaged: false }),
          e('session_completed', { hints: 0, reliability: r.chance(0.5) ? 'poor' : 'fair' }),
          e('random_responding'),
          e('break_suggested', { taken: false }),
          e('recommendation_response', { response: 'rejected', confidence: 'moderate', evidenceViewed: false }),
          e('pii_shared'),
        ]),
    },
    {
      name: 'Balanced, new user (5 interactions)',
      gen: (r, i) => (i < 5 ? r.pick([e('why_opened'), e('goal_self_set'), e('consent_informed'), e('session_completed', { hints: 0, hintsAvailable: true, reliability: 'good' })]) : null),
    },
  ];
  out('| Archetype | Mean ACS | SD across replications | Mean 80 % interval width |');
  out('|---|---|---|---|');
  for (const a of archetypes) {
    const totals: number[] = [];
    let widths = 0;
    for (let rep = 0; rep < 200; rep++) {
      const events = Array.from({ length: 40 }, (_, i) => a.gen(rng, i)).filter((x): x is AIEvent => x !== null);
      const s = computeCollabScore(events);
      totals.push(s.total);
      widths += s.hi - s.lo;
    }
    const m = totals.reduce((s, x) => s + x, 0) / totals.length;
    const sd = Math.sqrt(totals.reduce((s, x) => s + (x - m) ** 2, 0) / totals.length);
    out(`| ${a.name} | ${f(m, 1)} | ${f(sd, 1)} | ${f(widths / 200, 1)} |`);
  }
  out();
}

