/**
 * Generates docs/DIMENSIONS.md from the dimension registry (src/engine/dimensions.ts), so the
 * written documentation can never drift from what the app actually does.
 *
 *   npm run docs
 */
import { writeFileSync } from 'node:fs';
import { DIMENSIONS, GENERAL_REFERENCES, POPULATION_PRIOR, DRIFT_PER_DAY, DRIFT_PER_SESSION } from '../src/engine/index';

const out: string[] = [];
const w = (s = '') => out.push(s);

w('# Cognitive dimensions');
w();
w('> Generated by `npm run docs` from `src/engine/dimensions.ts`. Do not edit by hand.');
w();
w('CogniTwin profiles six dimensions, chosen to cover the core executive functions (Miyake et al., 2000; Diamond, 2013) plus the two capacities most often discussed alongside them — processing speed and fluid reasoning. Each dimension has one procedurally generated, language-free task with a 10-level difficulty ladder.');
w();
w('**Non-clinical by design.** Scores describe performance on these exercises, relative to the exercises themselves (criterion-referenced mastery), never a comparison with a population and never a statement about health.');
w();
w('## Shared measurement model');
w();
w('- Outcome per trial: *success* = correct **and** within the response window (windows are scaled by the personal device/motor calibration factor, 1.0–1.6).');
w('- Model: `P(success | θ, level) = c + (1 − c) · σ(a · (θ − b_level))`, `b_level` evenly spaced on [−2.25, 2.25].');
w(`- Prior for an unmeasured dimension: N(${POPULATION_PRIOR.mean}, ${POPULATION_PRIOR.sd}²). Posterior computed exactly on a 181-point grid, then summarised as a Gaussian for the Brain Twin.`);
w('- Percentage = expected mastery of the 10-level ladder at θ; the 80 % credible interval is the mastery of the θ quantiles (exact, because mastery is monotonic).');
w(`- Brain Twin drift: variance + ${DRIFT_PER_DAY} per idle day and + ${DRIFT_PER_SESSION} per session (capped at the prior).`);
w('- Data quality: sessions get a weight (0.2–1) from interruptions, implausibly fast responses and random-pressing detection; trials right after an interruption weigh 0.3, trials with a hint 0.6.');
w('- Confidence label from interval width: high ≤ 16 points, moderate ≤ 30, otherwise low.');
w();
w('| Dimension | Task | a | c | Check-in trials | Stop at σ ≤ | Training trials |');
w('|---|---|---|---|---|---|---|');
for (const d of DIMENSIONS) {
  const t = d.task;
  w(`| ${d.name} | ${t.name} | ${t.discrimination} | ${t.guessing} | ${t.assessment.minTrials}–${t.assessment.maxTrials} | ${t.assessment.targetSd} | ${t.trainingTrials} |`);
}
w();

for (const d of DIMENSIONS) {
  const t = d.task;
  w(`## ${d.name}`);
  w();
  w(`**Definition.** ${d.definition}`);
  w();
  w(`**Everyday examples.** ${d.everyday.join('; ')}.`);
  w();
  w(`**What it is not.** ${d.notThis}`);
  w();
  w(`### Task — ${t.name}`);
  w();
  w(`*${t.tagline}*`);
  w();
  t.instructions.forEach((i: string, k: number) => w(`${k + 1}. ${i}`));
  w();
  w(`Controls: ${t.controls}`);
  w();
  w('| Level | What makes it harder | Base response window |');
  w('|---|---|---|');
  for (let l = 1; l <= t.levels; l++) w(`| ${l} | ${t.levelDescription(l)} | ${(t.deadlineMs(l) / 1000).toFixed(1)} s |`);
  w();
  w('### Scoring');
  w();
  w(d.scoring);
  w();
  w('### Uncertainty');
  w();
  w(d.uncertainty);
  w();
  w('### Possible biases and mitigations');
  w();
  w('| Bias | Mitigation |');
  w('|---|---|');
  for (const b of d.biases) w(`| ${b.bias} | ${b.mitigation} |`);
  w();
  w('### Coaching strategies');
  w();
  for (const s of d.strategies) w(`- **${s.title}.** ${s.detail}${s.source ? ` *(${s.source})*` : ''}`);
  w();
  w('### Everyday missions (transfer)');
  w();
  for (const m of d.missions) w(`- ${m}`);
  w();
  w('### References');
  w();
  for (const r of d.references) w(`- ${r}`);
  w();
}

w('## General references');
w();
for (const r of GENERAL_REFERENCES) w(`- ${r}`);
w();

writeFileSync('docs/DIMENSIONS.md', out.join('\n'), 'utf8');
console.log(`docs/DIMENSIONS.md written (${out.length} lines)`);
