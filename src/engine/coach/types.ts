import type { Confidence, DimensionId, Evidence, SessionMode } from '../types';

export type CoachAction =
  | { kind: 'start_session'; taskId: string; mode: SessionMode; label: string }
  | { kind: 'create_goal'; dimension: DimensionId; target: number; deadlineDays: number; label: string }
  | { kind: 'take_break'; minutes: number; label: string }
  | { kind: 'open'; route: string; label: string };

export interface SafetyReport {
  passed: boolean;
  checks: string[];
  /** Violations found in a first LLM draft that were fixed by regeneration or fallback. */
  intercepted: string[];
  fallbackUsed: boolean;
  /** Safe, user-facing explanation; never raw provider diagnostics or credentials. */
  fallbackReason?: string;
}

export interface CoachMessage {
  id: string;
  role: 'coach' | 'user';
  text: string;
  at: number;
  headline?: string;
  /** Evidence behind the message — rendered in the "Why?" panel. */
  evidence: Evidence[];
  insightIds: string[];
  confidence: Confidence;
  source: 'template' | 'llm' | 'safe-reply' | 'user';
  safety?: SafetyReport;
  /** Quick-reply chips. */
  suggestions?: string[];
  /** A proposed action — never executed without the user's click. */
  action?: CoachAction;
  /** Intent detected for user messages / answered by coach messages. */
  intent?: string;
  /** Model id when generated by an LLM. */
  model?: string;
}
